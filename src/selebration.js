function pick(array) {
  return array[
    Math.floor(Math.random() * array.length)
  ];
}

export function createCelebration({
  completed
}) {
  if (completed) {
    return {
      dayWon: true,
      score: 10,
      text: pick(WIN_PHRASES)
    };
  }

  return {
    dayWon: false,
    score: 5,
    text: pick(GENTLE_PHRASES)
  };
}
